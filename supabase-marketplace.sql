create table if not exists public.farmers_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    display_name text not null default '' check (char_length(display_name) <= 60),
    role text not null default 'Farmer' check (char_length(role) <= 60),
    bio text not null default '' check (char_length(bio) <= 1000),
    experience text not null default '',
    location text not null default '',
    farm_type text not null default '',
    crops text[] not null default '{}',
    livestock text[] not null default '{}',
    phone text not null default '',
    show_location boolean not null default false,
    allow_messages boolean not null default true,
    updated_at timestamptz not null default now()
);

alter table public.farmers_profiles enable row level security;

drop policy if exists "Farmers can read their own profile" on public.farmers_profiles;
create policy "Farmers can read their own profile"
    on public.farmers_profiles for select
    to authenticated
    using (id = (select auth.uid()));

drop policy if exists "Farmers can create their own profile" on public.farmers_profiles;
create policy "Farmers can create their own profile"
    on public.farmers_profiles for insert
    to authenticated
    with check (id = (select auth.uid()));

drop policy if exists "Farmers can update their own profile" on public.farmers_profiles;
create policy "Farmers can update their own profile"
    on public.farmers_profiles for update
    to authenticated
    using (id = (select auth.uid()))
    with check (id = (select auth.uid()));

grant select, insert, update on public.farmers_profiles to authenticated;

create table if not exists public.market_listings (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    title text not null check (char_length(title) between 1 and 70),
    name text not null check (char_length(name) between 1 and 70),
    category text not null check (category in ('crops', 'livestock', 'poultry', 'fish', 'inputs')),
    price numeric(12, 2) not null check (price > 0),
    unit text not null check (char_length(unit) between 1 and 30),
    quantity integer not null check (quantity > 0),
    seller text not null check (char_length(seller) between 1 and 60),
    location text not null check (char_length(location) between 1 and 60),
    description text not null default '' check (char_length(description) <= 300),
    image_path text,
    image_url text,
    created_at timestamptz not null default now()
);

create table if not exists public.market_listing_contacts (
    listing_id bigint primary key references public.market_listings(id) on delete cascade,
    owner_id uuid not null references auth.users(id) on delete cascade,
    contact text not null check (char_length(contact) between 1 and 80)
);

create table if not exists public.market_offers (
    id uuid primary key default gen_random_uuid(),
    listing_id bigint not null references public.market_listings(id) on delete cascade,
    buyer_id uuid not null references auth.users(id) on delete cascade,
    buyer_name text not null check (char_length(buyer_name) between 1 and 60),
    amount numeric(12, 2) not null check (amount > 0),
    quantity integer not null check (quantity > 0),
    contact text not null check (char_length(contact) between 1 and 80),
    message text not null default '' check (char_length(message) <= 240),
    created_at timestamptz not null default now()
);

alter table public.market_listings enable row level security;
alter table public.market_listing_contacts enable row level security;
alter table public.market_offers enable row level security;

drop policy if exists "Anyone can view marketplace listings" on public.market_listings;
create policy "Anyone can view marketplace listings"
    on public.market_listings for select
    to anon, authenticated
    using (true);

drop policy if exists "Farmers can create their own listings" on public.market_listings;
create policy "Farmers can create their own listings"
    on public.market_listings for insert
    to authenticated
    with check (owner_id = (select auth.uid()));

drop policy if exists "Farmers can delete their own listings" on public.market_listings;
create policy "Farmers can delete their own listings"
    on public.market_listings for delete
    to authenticated
    using (owner_id = (select auth.uid()));

drop policy if exists "Owners can view their listing contact" on public.market_listing_contacts;
create policy "Owners can view their listing contact"
    on public.market_listing_contacts for select
    to authenticated
    using (owner_id = (select auth.uid()));

drop policy if exists "Anyone can view seller order phone numbers" on public.market_listing_contacts;
create policy "Anyone can view seller order phone numbers"
    on public.market_listing_contacts for select
    to anon, authenticated
    using (true);

drop policy if exists "Owners can add their listing contact" on public.market_listing_contacts;
create policy "Owners can add their listing contact"
    on public.market_listing_contacts for insert
    to authenticated
    with check (
        owner_id = (select auth.uid())
        and exists (
            select 1 from public.market_listings
            where id = listing_id and owner_id = (select auth.uid())
        )
    );

drop policy if exists "Owners can view offers for their listings and buyers can view their offers" on public.market_offers;
create policy "Owners can view offers for their listings and buyers can view their offers"
    on public.market_offers for select
    to authenticated
    using (
        buyer_id = (select auth.uid())
        or exists (
            select 1 from public.market_listings
            where id = listing_id and owner_id = (select auth.uid())
        )
    );

drop policy if exists "Buyers can submit offers" on public.market_offers;
create policy "Buyers can submit offers"
    on public.market_offers for insert
    to authenticated
    with check (
        buyer_id = (select auth.uid())
        and exists (
            select 1 from public.market_listings
            where id = listing_id
        )
    );

grant select on public.market_listings to anon, authenticated;
grant insert, delete on public.market_listings to authenticated;
grant select on public.market_listing_contacts to anon, authenticated;
grant insert on public.market_listing_contacts to authenticated;
grant select, insert on public.market_offers to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
