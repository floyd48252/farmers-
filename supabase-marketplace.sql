drop policy if exists "Anyone can view marketplace product photos" on storage.objects;
create policy "Anyone can view marketplace product photos"
    on storage.objects for select
    to anon, authenticated
    using (bucket_id = 'market-product-images');

drop policy if exists "Farmers can upload their own marketplace photos" on storage.objects;
create policy "Farmers can upload their own marketplace photos"
    on storage.objects for insert
    to authenticated
    with check (
        bucket_id = 'market-product-images'
        and (storage.foldername(name))[1] = (select auth.uid())::text
    );

drop policy if exists "Farmers can delete their own marketplace photos" on storage.objects;
create policy "Farmers can delete their own marketplace photos"
    on storage.objects for delete
    to authenticated
    using (
        bucket_id = 'market-product-images'
        and (storage.foldername(name))[1] = (select auth.uid())::text
    );

